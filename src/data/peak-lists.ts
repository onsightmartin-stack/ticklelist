import { countries as allCountries } from "@/data/countries";
import { polandPowiatKeys } from "@/data/poland-powiats";

/**
 * Curated "tick lists" members can try to complete.
 * Each entry points at catalog keys: `hp:<Country>` for country high points,
 * `fp:<Peak name>` for famous peaks. `alt` keys count as the same tick
 * (e.g. Kosciuszko logged as Australia's high point).
 */
export interface PeakListEntry {
  key: string;
  alt?: string[];
}

export interface PeakList {
  id: string;
  name: string;
  blurb: string;
  category: "Classic" | "Regional" | "Volcanic" | "Extreme";
  entries: PeakListEntry[];
}

const hp = (...countries: string[]): PeakListEntry[] =>
  countries.map((c) => ({ key: `hp:${c}` }));

/** All 193 UN member states, ordered by continent then elevation as in the catalog. */
const unMemberEntries: PeakListEntry[] = allCountries
  .filter((c) => c.unMember !== false && c.country !== "Antarctica")
  .map((c) => ({ key: `hp:${c.country}` }));

/**
 * Mainland high points: the official country high point, except where it sits
 * on an overseas territory or offshore island — then the mainland summit.
 */
const mainlandOverrides: Record<string, PeakListEntry> = {
  Denmark: { key: "fp:Møllehøj" },
  Netherlands: { key: "fp:Vaalserberg" },
  Spain: { key: "fp:Mulhacén" },
  Portugal: { key: "fp:Torre" },
  "United Kingdom": { key: "fp:Ben Nevis" },
  Australia: { key: "fp:Kosciuszko", alt: ["hp:Australia"] },
  "Equatorial Guinea": { key: "fp:Monte Chocolate" },
  Malaysia: { key: "fp:Gunung Tahan" },
};

const mainlandEntries: PeakListEntry[] = allCountries
  .filter((c) => c.country !== "Antarctica")
  .map((c) => mainlandOverrides[c.country] ?? { key: `hp:${c.country}` });


